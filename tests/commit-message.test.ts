import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  utimesSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import test, { type TestContext } from "node:test";

function messageFile(t: TestContext, message: string) {
  const directory = mkdtempSync(join(tmpdir(), "prowl-commit-message-"));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const path = join(directory, "message with spaces");
  writeFileSync(path, message);
  return path;
}

function clean(path: string) {
  const result = spawnSync(
    process.execPath,
    [resolve("scripts/clean-commit-message.mjs"), path],
    { encoding: "utf8" },
  );
  assert.equal(result.status, 0, result.stderr);
  return readFileSync(path, "utf8");
}

test("removes AI author and generated signatures while preserving human trailers", (t) => {
  const signatures = [
    "Co-Authored-By: Claude <noreply@anthropic.com>",
    "authored by: Claude Code",
    "Co-authored-by: Claude Sonnet 4.6 <noreply@anthropic.com>",
    "Co-authored-by: Claude Opus 4.6 <noreply@anthropic.com>",
    "Co-authored-by: ChatGPT <bot@example.com>",
    "Co-authored-by: OpenAI Codex <bot@example.com>",
    "Co-authored-by: Codex <bot@example.com>",
    "Co-authored-by: GitHub Copilot <bot@example.com>",
    "Co-authored-by: Copilot <bot@example.com>",
    "Co-authored-by: Cursor <bot@example.com>",
    "Co-authored-by: Gemini <bot@example.com>",
    "🤖 Generated with [Claude Code](https://claude.ai/code)",
    "Generated by ChatGPT",
  ];
  const before = "Improve the form\n\nKeep names varied — Zoë.\n\n";
  const after =
    "Co-authored-by: Josh Karp <josh@example.com>\nSigned-off-by: Reviewer <reviewer@example.com>\n";
  const path = messageFile(t, before + signatures.join("\n") + "\n" + after);
  assert.equal(clean(path), before + after);
});

test("preserves normal prose, unknown identities and quoted AI footer examples without rewriting", (t) => {
  const message =
    "Document Claude integration\n\nGenerated data is authored by people.\n" +
    "> Co-authored-by: Claude <noreply@anthropic.com>\n" +
    "```text\nCo-authored-by: Claude <noreply@anthropic.com>\n```\n" +
    "~~~\nGenerated by Codex\n~~~\n\n" +
    "Co-authored-by: Claude Smith <claude@example.com>\n" +
    "Co-authored-by: Unknown Tool <tool@example.com>\n";
  const path = messageFile(t, message);
  utimesSync(path, new Date(0), new Date(0));
  const modified = statSync(path).mtimeMs;
  assert.equal(clean(path), message);
  assert.equal(statSync(path).mtimeMs, modified);
});

test("preserves CRLF line endings and supports messages without a final newline", (t) => {
  const path = messageFile(
    t,
    "Update form\r\n\r\nCo-authored-by: Claude Code <noreply@anthropic.com>\r\nCo-authored-by: Human <human@example.com>",
  );
  assert.equal(
    clean(path),
    "Update form\r\n\r\nCo-authored-by: Human <human@example.com>",
  );
});
